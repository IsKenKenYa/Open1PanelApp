    <String, Object?>{'cpu': 1.5, 'memory': 2.5, 'load1': 0.4},
    '{"cpu":1.5,"memory":2.5,"load1":0.4}',
  ),
];

/// (错误码, 错误消息, details)
final _errorCases = <(String, String?, Object?)>[
  ('error', 'Missing method for channel call', null),
  ('server_error', 'upstream failed', 'ctx-1'),
];

// ── 生成逻辑 ────────────────────────────────────────────────────────────────

String _hex(ByteData data) {
  final bytes = data.buffer.asUint8List(data.offsetInBytes, data.lengthInBytes);
  return bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
}

String _csString(String value) =>
    '"${value.replaceAll('\\', r'\\').replaceAll('"', r'\"')}"';

const _codec = StandardMethodCodec();

String _renderGoldenFile() {
  final sb = StringBuffer();
  sb.writeln('// <auto-generated>');
  sb.writeln('// 由 test/core/channel/winui_codec_golden_test.dart 生成'
      '（ONEPANEL_REGEN_GOLDEN=1），请勿手改。');
  sb.writeln('// Hex 为 Dart StandardMethodCodec 的真实编码字节，'
      '是 C# WindowsBridge.Codec 的 golden 向量。');
  sb.writeln('// </auto-generated>');
  sb.writeln('namespace OnePanelNativeHost.Tests;');
  sb.writeln();
  sb.writeln('public static class GoldenVectors');
  sb.writeln('{');

  sb.writeln('    public static readonly (string Name, string Hex)[] MethodCalls =');
  sb.writeln('    {');
  for (final (name, args, _) in _methodCallCases) {
    final bytes = _codec.encodeMethodCall(MethodCall(name, args));
    sb.writeln('        (${_csString(name)}, ${_csString(_hex(bytes))}),');
  }
  sb.writeln('    };');
  sb.writeln();

  sb.writeln('    public static readonly (string Name, string Hex, string ExpectedJson)[] SuccessResponses =');
  sb.writeln('    {');
  var successIndex = 0;
  for (final (value, expectedJson) in _successCases) {
    final bytes = _codec.encodeSuccessEnvelope(value);
    sb.writeln(
      '        (${_csString('success_$successIndex')}, '
      '${_csString(_hex(bytes))}, ${_csString(expectedJson)}),',
    );
    successIndex++;
  }
  sb.writeln('    };');
  sb.writeln();

  sb.writeln('    public static readonly (string Name, string Hex)[] ErrorResponses =');
  sb.writeln('    {');
  var errorIndex = 0;
  for (final (code, message, details) in _errorCases) {
    final bytes = _codec.encodeErrorEnvelope(code: code, message: message, details: details);
    sb.writeln('        (${_csString('error_$errorIndex')}, ${_csString(_hex(bytes))}),');
    errorIndex++;
  }
  sb.writeln('    };');
  sb.writeln('}');
  return sb.toString();
}
