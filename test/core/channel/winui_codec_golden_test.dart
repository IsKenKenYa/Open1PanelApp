import 'dart:io';

import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';

/// WinUI C# 端 WindowsBridge.Codec 的 golden 向量测试。
///
/// 事实源是 Dart `StandardMethodCodec` 的真实编码字节：
/// - 常规运行：断言 `GoldenVectors.g.cs` 与当前 Dart 编码输出一致（防两端漂移）。
/// - `ONEPANEL_REGEN_GOLDEN=1` 运行：重新生成 `GoldenVectors.g.cs`。
///
/// ExpectedJson 是按 System.Text.Json 默认序列化约定手写的期望值，
/// 独立于 C# 代码路径，避免自证。
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  const goldenRelativePath =
      'windows/runner/native_host/OnePanelNativeHost.Tests/GoldenVectors.g.cs';

  test('WinUI C# golden vectors 与 Dart StandardMethodCodec 保持同步', () {
    final generated = _renderGoldenFile();
    final file = File(goldenRelativePath);

    if (Platform.environment['ONEPANEL_REGEN_GOLDEN'] == '1') {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(generated);
      return;
    }

    expect(
      file.existsSync(),
      isTrue,
      reason: '缺少 $goldenRelativePath，'
          '请运行 ONEPANEL_REGEN_GOLDEN=1 flutter test '
          'test/core/channel/winui_codec_golden_test.dart 生成',
    );
    final onDisk = file.readAsStringSync().replaceAll('\r\n', '\n');
    expect(
      onDisk,
      generated,
      reason: 'GoldenVectors.g.cs 与 Dart StandardMethodCodec 当前输出不一致；'
          '若为预期变更，请运行 ONEPANEL_REGEN_GOLDEN=1 重新生成并同步 C# 侧',
    );
  });
}

// ── 用例表 ──────────────────────────────────────────────────────────────────

/// (方法名, Dart 参数值, C# 等价构造)
