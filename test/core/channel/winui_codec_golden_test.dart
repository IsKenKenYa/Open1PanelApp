/// (成功响应值, 手写期望 JSON —— System.Text.Json 默认约定)
final _successCases = <(Object?, String)>[
  (null, 'null'),
  (true, 'true'),
  (42, '42'),
  (-7, '-7'),
  (3000000000, '3000000000'),
  (3.14, '3.14'),
  ('ok', '"ok"'),
  (<Object?>[], '[]'),
  (<String, Object?>{}, '{}'),
  (
    <Object?>[
      <String, Object?>{
        'id': 'srv-001',
        'name': 'Production',
        'isCurrent': true,
        'cpu': 12.5,
      },
    ],
    '[{"id":"srv-001","name":"Production","isCurrent":true,"cpu":12.5}]',
