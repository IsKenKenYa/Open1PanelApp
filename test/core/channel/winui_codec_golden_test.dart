  ('getServers', null, 'null'),
  (
    'getFiles',
    <String, Object?>{'path': '/'},
    'new Dictionary<string, object?> { ["path"] = "/" }',
  ),
  ('getCurrentServer', null, 'null'),
  (
    'switchServer',
    <String, Object?>{'id': 'srv-001'},
    'new Dictionary<string, object?> { ["id"] = "srv-001" }',
  ),
  (
    'updateSetting',
    <String, Object?>{'key': 'app_lock_enabled', 'value': true},
    'new Dictionary<string, object?> { ["key"] = "app_lock_enabled", ["value"] = true }',
  ),
